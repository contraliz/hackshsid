"""Reproduce the named synthetic scenarios and carbon-weight sensitivity."""

from __future__ import annotations

import csv
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.scheduler import run_comparison

RESULTS = ROOT / "results"
SCENARIOS = [
    ("Balanced day", {"scenario": "baseline", "carbon_weight": 0.35}),
    ("Evening price spike", {"scenario": "price-spike", "carbon_weight": 0.35}),
    ("Renewables shortage", {"scenario": "renewables-shortage", "carbon_weight": 0.35}),
    ("Demand surge", {"scenario": "demand-surge", "carbon_weight": 0.35}),
    ("Cost only", {"scenario": "baseline", "carbon_weight": 0.0}),
    ("High carbon weight", {"scenario": "baseline", "carbon_weight": 0.8}),
]


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    records = []
    for label, controls in SCENARIOS:
        result = run_comparison(controls)
        baseline = result["baseline"]["metrics"]
        optimized = result["optimized"]["metrics"] if result["optimized"] else {}
        records.append({
            "case": label,
            "scenario_id": controls["scenario"],
            "seed": result["case"]["seed"],
            "gpu_count": result["case"]["gpu_count"],
            "demand_scale": result["case"]["demand_scale"],
            "renewable_scale": result["case"]["renewable_scale"],
            "carbon_weight_cu_per_kg": result["case"]["carbon_weight"],
            "solver_status": result["optimizer"]["status"],
            "baseline_status": result["baseline"]["status"],
            "baseline_cost_cu": baseline["grid_cost_units"],
            "optimized_cost_cu": optimized.get("grid_cost_units"),
            "cost_savings_pct": result["comparison"]["cost_savings_pct"],
            "baseline_emissions_kg": baseline["grid_emissions_kg_co2e"],
            "optimized_emissions_kg": optimized.get("grid_emissions_kg_co2e"),
            "emissions_change_pct": result["comparison"]["emissions_change_pct"],
            "baseline_deadlines_met": f"{baseline['deadlines_met']}/{baseline['deadline_count']}",
            "optimized_deadlines_met": f"{optimized.get('deadlines_met', 0)}/{optimized.get('deadline_count', len(result['case']['jobs']))}",
            "baseline_unmet_gpu_hours": baseline["flexible_gpu_hours_unmet"],
            "solve_time_ms": result["optimizer"]["solve_time_seconds"] * 1000,
            "comparable": result["comparison"]["comparable"],
        })

    csv_path = RESULTS / "scenario_comparison.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)

    md_path = RESULTS / "scenario_comparison.md"
    with md_path.open("w", encoding="utf-8") as handle:
        handle.write("# Synthetic scenario comparison\n\n")
        handle.write("Generated by `python scripts/run_experiments.py`; inputs use deterministic seed 2026. These are simulated results, not measured data-center performance.\n\n")
        handle.write("| Case | Solver | ASAP cost (CU) | Optimized cost (CU) | Cost change | ASAP emissions (kgCO₂e) | Optimized emissions (kgCO₂e) | Emissions change | Deadlines (ASAP → LP) | Comparable |\n")
        handle.write("|---|---:|---:|---:|---:|---:|---:|---:|---|---|\n")
        for row in records:
            def shown(value: object, precision: int = 2) -> str:
                return "—" if value is None else f"{float(value):.{precision}f}"
            cost_change = "—" if row["cost_savings_pct"] is None else f"{float(row['cost_savings_pct']):+.2f}%"
            carbon_change = "—" if row["emissions_change_pct"] is None else f"{float(row['emissions_change_pct']):+.2f}%"
            handle.write(
                f"| {row['case']} | {row['solver_status']} | {shown(row['baseline_cost_cu'])} | "
                f"{shown(row['optimized_cost_cu'])} | {cost_change} | {shown(row['baseline_emissions_kg'])} | "
                f"{shown(row['optimized_emissions_kg'])} | {carbon_change} | {row['baseline_deadlines_met']} → "
                f"{row['optimized_deadlines_met']} | {row['comparable']} |\n"
            )
        handle.write("\nPositive percentage changes in this table mean reductions computed as (ASAP − optimized) / ASAP. A dash means the solver was infeasible or the baseline did not complete all jobs, so an apples-to-apples percentage is unavailable.\n")
        handle.write("\nThe energy model includes a constant base load, and hourly renewable supply is consumed first. Moving flexible work can change price/emissions exposure without changing total GPU-hours or total renewable availability. The demand-surge case is intentionally stressful and may be infeasible.\n")
    print(f"Wrote {csv_path}")
    print(f"Wrote {md_path}")
    for row in records:
        print(f"{row['case']}: {row['solver_status']}; cost change={row['cost_savings_pct']}; emissions change={row['emissions_change_pct']}; deadlines={row['baseline_deadlines_met']}->{row['optimized_deadlines_met']}")


if __name__ == "__main__":
    main()
